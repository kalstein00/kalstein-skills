'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
test('unchanged projects retain their input identity when inferred declarations resolve package subpaths',t=>{
  const temp=fs.realpathSync(os.tmpdir()),root=fs.mkdtempSync(path.join(temp,'dart-project-surface-'));
  t.after(()=>{assert.equal(path.dirname(path.resolve(root)),temp);assert.ok(path.basename(root).startsWith('dart-project-surface-'));fs.rmSync(root,{recursive:true,force:true});});
  const write=(p,s)=>{fs.mkdirSync(path.dirname(path.join(root,p)),{recursive:true});fs.writeFileSync(path.join(root,p),s);};
  write('tsconfig.json',JSON.stringify({compilerOptions:{strict:true,module:'esnext',moduleResolution:'bundler',types:[]},include:['*.ts']}));
  write('node_modules/example/package.json',JSON.stringify({name:'example',version:'1.0.0',main:'lib/index.js',types:'lib/index.d.ts'}));
  write('node_modules/example/lib/index.d.ts','import { Value } from "./values"; export declare function make(): Value;');
  write('node_modules/example/lib/values/index.d.ts','export declare class Value { n: number }');
  write('main.ts','import { make } from "example"; export const result = make();');
  write('other.ts','export const other = 1;');
  const api=require('./project-surface.cjs');
  const prepared=api.prepareProjectInput(root,'tsconfig.json');
  const collected=api.collectProjectSurface(root,'tsconfig.json',['main.ts']);
  assert.equal(collected.status,'complete');
  assert.deepEqual(collected.files.map(file=>file.path),['main.ts']);
  assert.equal(collected.files[0].metric.population,1);
  assert.match(collected.files[0].declaration,/Value/);
  assert.equal(api.verifyProjectInput(prepared.input),true);
  assert.equal(api.verifyProjectInput(collected.input),true);
  assert.equal(prepared.identity,collected.inputIdentity);
  assert.equal(api.collectProjectSurface(root,'tsconfig.json',['other.ts']).inputIdentity,prepared.identity);
  assert.equal(fs.existsSync(path.join(root,'main.d.ts')),false);
  assert.equal(fs.existsSync(path.join(root,'other.d.ts')),false);
  write('node_modules/example/lib/values.d.cts','export declare class Value { changed: string }');
  assert.equal(api.verifyProjectInput(prepared.input),false,'new declaration resolution candidates must invalidate preparation');
  assert.equal(api.verifyProjectInput(collected.input),false,'new declaration resolution candidates must invalidate collection');
});
test('explicit project resolves types and records dependency drift without confusing body changes',t=>{
  const temp=fs.realpathSync(os.tmpdir()),root=fs.mkdtempSync(path.join(temp,'dart-project-surface-'));
  t.after(()=>{assert.equal(path.dirname(path.resolve(root)),temp);assert.ok(path.basename(root).startsWith('dart-project-surface-'));fs.rmSync(root,{recursive:true,force:true});});
  const write=(p,s)=>{fs.mkdirSync(path.dirname(path.join(root,p)),{recursive:true});fs.writeFileSync(path.join(root,p),s);};
  write('tsconfig.json',JSON.stringify({compilerOptions:{strict:true,baseUrl:'.',paths:{types:['types.d.ts']}},include:['*.ts']}));
  write('types.d.ts','export interface Value { n: number }');write('main.ts','import {Value} from "types"; export function f(v:Value):number { return v.n; }');
  const api=require('./project-surface.cjs');
  const a=api.collectProjectSurface(root,'tsconfig.json',['main.ts']);assert.equal(a.status,'complete');assert.equal(a.files[0].validity,'valid');assert.equal(a.files[0].metric.value,1);
  assert.equal(api.verifyProjectInput(a.input),true);
  assert.equal(api.prepareProjectInput(root,'tsconfig.json').identity,a.inputIdentity);
  write('main.ts','import {Value} from "types"; export function f(v:Value):number { return v.n + 1; }');
  assert.equal(api.verifyProjectInput(a.input),false);const b=api.collectProjectSurface(root,'tsconfig.json',['main.ts']);assert.equal(a.files[0].fingerprint,b.files[0].fingerprint);assert.notEqual(a.inputIdentity,b.inputIdentity);
  write('types.d.ts','export interface Value { n: number; name: string }');assert.equal(api.verifyProjectInput(b.input),false);
  const c=api.prepareProjectInput(root,'tsconfig.json');assert.notEqual(c.identity,b.inputIdentity);
  write('main.ts','export const broken = missing();');const bad=api.collectProjectSurface(root,'tsconfig.json',['main.ts']);assert.equal(bad.status,'partial');assert.equal(bad.files[0].fingerprint,null);assert.ok(bad.diagnostics.length);assert.ok(bad.files[0].reason.length<200);
  assert.throws(()=>api.prepareProjectInput(root,'absent.json'),/config/i);
  write('main.ts','export const a=1;');write('other.ts','export const b=2;');
  write('tsconfig.json',JSON.stringify({compilerOptions:{module:'amd',outFile:'bundle.js'},include:['*.ts']}));
  assert.throws(()=>api.collectProjectSurface(root,'tsconfig.json',['main.ts','other.ts']),/outFile/);
});
